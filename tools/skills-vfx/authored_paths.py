"""Reproduce native arrow contacts from the original Spine mesh/deform data.

This is a maintained data importer, not a runtime simulation. The explicit
import-native publication writes this result and the matching source skeleton
in one revision-checked transaction. Standalone output must stay external.
"""
import argparse,bisect,hashlib,json,math
from pathlib import Path

def encoded(data):
 return (json.dumps(data,ensure_ascii=False,indent=2,allow_nan=False)+'\n').encode('utf-8')

def deformation(keys,time,size):
 if not keys or time<keys[0].get('time',0)-1e-7:return [0.]*size
 index=max(0,bisect.bisect_right([key.get('time',0) for key in keys],time+1e-7)-1)
 def vector(key):
  values=[0.]*size;offset=key.get('offset',0);points=key.get('vertices',[])
  if offset<0 or offset+len(points)>size:raise ValueError('Invalid sparse mesh deformation')
  values[offset:offset+len(points)]=points;return values
 left=keys[index];values=vector(left)
 if index+1>=len(keys):return values
 right=keys[index+1];span=right.get('time',0)-left.get('time',0)
 if span<=0:return values
 amount=max(0.,min(1.,(time-left.get('time',0))/span));curve=left.get('curve')
 if curve=='stepped':amount=0
 elif curve is not None:raise ValueError('New Bezier deform curves require an explicitly verified sampler')
 return [a+(b-a)*amount for a,b in zip(values,vector(right))]

def sample(data):
 animation=data['animations']['animation'];skins=data['skins'][0]['attachments'];paths=[]
 flashes=sorted({round(next(k.get('time',0) for k in t['attachment'] if k.get('name'))*120)/120 for slot,t in animation['slots'].items() if 'fashe' in slot})
 gathering=sorted({round(next(k.get('time',0) for k in t['attachment'] if k.get('name'))*120)/120 for slot,t in animation['slots'].items() if 'jujijian' in slot})
 if len(flashes)!=3 or len(gathering)!=3:raise ValueError('The three authored volley release flashes changed')
 if animation.get('bones'):raise ValueError('Animated source bones need verified world-space sampling')
 bones=data.get('bones',[])
 if len(bones)!=1 or any(bones[0].get(key,default)!=default for key,default in [('x',0),('y',0),('rotation',0),('scaleX',1),('scaleY',1)]):raise ValueError('Source root transform changed')
 for slot,timeline in animation['slots'].items():
  if 'jujijian' not in slot:continue
  attachments=timeline['attachment'];first=next(key.get('time',0) for key in attachments if key.get('name'))
  volley=min(range(3),key=lambda i:abs(first-gathering[i]));release=flashes[volley];points=[]
  for frame in range(round(release*120),241):
   time=frame/120;keys=[key for key in attachments if key.get('time',0)<=time+1e-7];name=keys[-1].get('name') if keys else None
   if name is None:continue
   attachment=skins[slot][name];vertices=attachment['vertices']
   if len(vertices)!=len(attachment['uvs']):raise ValueError('Weighted source arrows require world-space sampling')
   delta=deformation(animation.get('deform',{}).get('default',{}).get(slot,{}).get(name,[]),time,len(vertices))
   vertices=[a+b for a,b in zip(vertices,delta)];count=len(vertices)/2
   x=sum(vertices[::2])/count;y=sum(vertices[1::2])/count
   radius=min(math.hypot(vertices[2]-vertices[0],vertices[3]-vertices[1]),math.hypot(vertices[4]-vertices[2],vertices[5]-vertices[3]))/2
   points.append(dict(t=round(time,7),x=round(x,4),y=round(y,4),radius=round(radius,4)))
  if not points:raise ValueError('An authored arrow has no visible flight')
  paths.append(dict(slot=slot,volley=volley,release=release,end=points[-1]['t'],points=points))
 if len(paths)!=9 or any(sum(p['volley']==i for p in paths)!=3 for i in range(3)):raise ValueError('The authored three-by-three volley changed')
 starts=[p['points'][0] for p in paths];ends=[p['points'][-1] for p in paths]
 angle=math.degrees(math.atan2(sum(b['y']-a['y'] for a,b in zip(starts,ends)),sum(b['x']-a['x'] for a,b in zip(starts,ends))))
 first=[p['points'][0] for p in paths if p['volley']==0]
 return dict(sourceSha256=hashlib.sha256(encoded(data)).hexdigest(),sourceOrigin=dict(x=sum(p['x'] for p in first)/3,y=sum(p['y'] for p in first)/3),sourceAngle=angle,defaultRotation=-angle,defaultScale=.16,duration=2,deformationSampled=True,firingTimes=flashes,trajectories=paths)

def module(data):
 return ('"use strict";\n// Generated by tools/skills-vfx/import-native.py from exact 120 Hz mesh deformation.\nmodule.exports = '+json.dumps(data,separators=(',',':'),allow_nan=False)+';\n').encode('utf-8')

if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('source',type=Path);parser.add_argument('output',type=Path);args=parser.parse_args()
 root=Path(__file__).resolve().parents[2]
 if args.output.resolve().is_relative_to(root):raise ValueError('Standalone samples must remain outside the repository; use import-native.py for publication')
 result=sample(json.loads(args.source.read_text(encoding='utf-8')));args.output.write_bytes(encoded(result))
