"""Publish only weather captures from the isolated combined VFX bake.

Stable IDs, strict manifest validation and revision-checked backups match the
hero importer. This publishes a separate catalog and never modifies hero VFX.
"""
import argparse, hashlib, json, math, re, sys
from pathlib import Path
from PIL import Image
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'tools/characters'))
from import_units import Transaction, asset_uuid, texture_meta

def capture_rows(bake):
    spec = json.loads(Path(__file__).with_name('weather-effects.json').read_text())
    expected = {row['id']: row for row in spec['clips']}
    jobs = json.loads((bake/'jobs.json').read_text())['clips']
    rows = json.loads((bake/'Baked/clips.json').read_text())['clips']
    source = json.loads((bake/'source.json').read_text())
    if len(expected) != len(spec['clips']): raise ValueError('Duplicate weather selection')
    selected, planned = {}, {}
    for values, target in ((jobs, planned), (rows, selected)):
        for row in values:
            ident = row.get('id')
            if ident not in expected: continue
            if ident in target: raise ValueError('Duplicate weather capture: '+ident)
            target[ident] = row
        if target.keys() != expected.keys(): raise ValueError('Incomplete weather capture manifest')
    if not re.fullmatch(r'[a-f0-9]{64}', source.get('workbookSha256', '')): raise ValueError('Invalid workbook provenance')
    for ident, row in selected.items():
        job, wanted = planned[ident], expected[ident]
        if row.get('file') != ident+'.png': raise ValueError('Unsafe capture path')
        for key in ('id','package','prefab','frames','fps','loop','slot','phase','group'):
            if row.get(key) != job.get(key) or row.get(key) != wanted.get(key): raise ValueError('Capture differs from weather selection: '+ident+' '+key)
        for key, maximum in (('frames',128),('fps',120),('columns',16),('cell',128)):
            if type(row.get(key)) is not int or not 1 <= row[key] <= maximum: raise ValueError('Invalid weather layout')
        if type(row.get('loop')) is not bool or not row['loop']: raise ValueError('Weather must loop')
        if row['columns']*row['cell'] > 2048 or math.ceil(row['frames']/row['columns'])*row['cell'] > 2048: raise ValueError('Weather atlas too large')
        for key in ('anchorX','anchorY','aspect'):
            value = row.get(key)
            if not isinstance(value,(int,float)) or isinstance(value,bool) or not math.isfinite(value): raise ValueError('Invalid weather pivot')
        if row['aspect'] <= 0 or type(row.get('visibleFrames')) is not int or not 0 < row['visibleFrames'] <= row['frames']: raise ValueError('Empty weather capture')
        bounds = row.get('alphaBounds')
        if not isinstance(bounds,list) or len(bounds)!=4 or any(type(n) is not int for n in bounds) or not (0<=bounds[0]<=bounds[2]<row['cell'] and 0<=bounds[1]<=bounds[3]<row['cell']): raise ValueError('Invalid weather alpha bounds')
    return list(selected.values()), source

def run(bake, backups):
    rows, source = capture_rows(bake)
    tx, clips = Transaction(ROOT,backups), []
    base = 'assets/resources/vfx/weather'
    tx.folder('assets/resources/vfx'); tx.folder(base)
    for row in rows:
        image, relative = bake/'Baked'/row['file'], base+'/'+row['file']
        raw = image.read_bytes()
        with Image.open(image) as im:
            width,height = im.size
            if im.mode!='RGBA' or width!=row['columns']*row['cell'] or height!=math.ceil(row['frames']/row['columns'])*row['cell']: raise ValueError('Invalid weather atlas dimensions')
            im.verify()
        meta=texture_meta(relative,width,height); existing=tx.read(relative+'.meta')
        if existing is not None and json.loads(existing)!=meta: raise ValueError('Preserve edited weather metadata before reimport: '+relative)
        tx.stage(relative,raw);tx.json(relative+'.meta',meta)
        fields=('id','name','loop','frames','columns','cell','fps','anchorX','anchorY','aspect','alphaBounds','visibleFrames')
        clip={key:row[key] for key in fields if key in row}
        clip.update(kind='flipbook',resource='vfx/weather/'+row['id'],uuid=asset_uuid(relative+'#sprite'),sha256=hashlib.sha256(raw).hexdigest(),source={'package':row['package'],'prefab':row['prefab']})
        clips.append(clip)
    catalog={'version':1,'workbookSha256':source['workbookSha256'],'clips':clips}
    tx.json(base+'/catalog.json',catalog)
    tx.json(base+'/catalog.json.meta',{'ver':'1.0.2','uuid':asset_uuid(base+'/catalog.json'),'importer':'json','subMetas':{}})
    script='assets/_script/WeatherVFXCatalog.js'
    tx.stage(script,b'"use strict";\n// Generated by tools/skills-vfx/import-weather-bake.py.\nmodule.exports = '+json.dumps(catalog,ensure_ascii=False,indent=2).encode()+b';\n')
    tx.json(script+'.meta',{'ver':'1.1.0','uuid':asset_uuid(script),'importer':'javascript','isPlugin':False,'loadPluginInWeb':True,'loadPluginInNative':True,'loadPluginInEditor':False,'subMetas':{}})
    print(json.dumps({'weatherClips':len(clips),'transaction':tx.commit()},indent=2))
if __name__=='__main__':
    parser=argparse.ArgumentParser(); parser.add_argument('bake',type=Path); parser.add_argument('backups',type=Path)
    args=parser.parse_args(); run(args.bake,args.backups)
